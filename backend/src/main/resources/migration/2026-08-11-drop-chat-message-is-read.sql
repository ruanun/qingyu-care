-- ============================================================
-- 删除 chat_message.is_read 死列（字段已建但全库无人读写，2026-08-11 选择删而非补特性）
--
-- 背景：这个字段建表时就有，但**全库从未被读写过**——没有任何接口回执已读状态，
-- 没有任何查询按它过滤，前端与 widget 也一次都没引用过它。它是「已读/送达」这个
-- 未实现特性留下的半截脚手架。
--
-- 为什么删而不是把特性做出来：已读/送达是一个完整的产品特性（后端回执接口 +
-- RealtimeNotifier 推送 + 管理端与 widget 两端展示），不该为了消一条技术债而候着做。
-- 字段现在无人读写，删了不影响任何行为；将来真要做，重新加回来的成本远小于
-- 让一个永远为 false 的列继续误导下一个读代码的人（「哦这里有已读状态」——其实没有）。
--
-- 为什么需要这个脚本：JPA 的 ddl-auto: update **只加不删**，实体里去掉字段之后
-- 存量库里那一列会一直留着。不执行本脚本的后果只是「多一列废数据」，不影响功能，
-- 但那正好又变成一条新的、更隐蔽的债。
--
-- 幂等：IF EXISTS，重复执行无害。
--
-- 一次性手动执行（项目未接入 Flyway/Liquibase）：
--   docker exec -i qingyu-postgres psql -U postgres -d qingyu_care \
--     < backend/src/main/resources/migration/2026-08-11-drop-chat-message-is-read.sql
--
-- ⚠️ 执行前先确认这一列真的没被用起来（若某个分支已经开始做已读特性，先别删）：
--   SELECT count(*) FROM chat_message WHERE is_read IS TRUE;
-- 预期是 0——非 0 说明有人已经在写它了，此时应停下来先弄清是谁。
-- ============================================================

ALTER TABLE chat_message DROP COLUMN IF EXISTS is_read;
